private void loadBookingHistory() {

    String sql =
        "SELECT booking_id, customer_name, contact_number, "
        + "pickup_location, dropoff_location, pickup_date, pickup_time "
        + "FROM bookings ORDER BY booking_id DESC";

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
            tableBookingHistory.getModel();

    model.setRowCount(0);

    try (java.sql.Connection con = DBConnection.connect();
         java.sql.PreparedStatement pst = con.prepareStatement(sql);
         java.sql.ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("booking_id"),
                rs.getString("customer_name"),
                rs.getString("contact_number"),
                rs.getString("pickup_location"),
                rs.getString("dropoff_location"),
                rs.getDate("pickup_date"),
                rs.getTime("pickup_time")
            });
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading booking history:\n" + e.getMessage()
        );
    }
}
private void updateRecordCount() {
    int total = tableBookingHistory.getRowCount();
    lblTotalRecords.setText("Total Records: " + total);
}
private void searchBookings() {

    String keyword = txtSearchBooking.getText().trim();

    if (keyword.isEmpty()) {
        loadBookingHistory();
        return;
    }

    String sql =
        "SELECT booking_id, customer_name, contact_number, "
        + "pickup_location, dropoff_location, pickup_date, pickup_time "
        + "FROM bookings "
        + "WHERE CAST(booking_id AS CHAR) = ? "
        + "OR customer_name LIKE ? "
        + "ORDER BY booking_id DESC";

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        tableBookingHistory.getModel();

    model.setRowCount(0);

    try (java.sql.Connection con = DBConnection.connect();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, keyword);
        pst.setString(2, "%" + keyword + "%");

        try (java.sql.ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("booking_id"),
                    rs.getString("customer_name"),
                    rs.getString("contact_number"),
                    rs.getString("pickup_location"),
                    rs.getString("dropoff_location"),
                    rs.getDate("pickup_date"),
                    rs.getTime("pickup_time")
                });
            }
            
            if (model.getRowCount() == 0) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "No bookings found for: " + keyword,
        "Search Result",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
}
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error searching bookings:\n" + e.getMessage()
        );
    }
    updateRecordCount();
}

