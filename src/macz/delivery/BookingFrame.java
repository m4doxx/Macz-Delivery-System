    private void createBooking() {

    String selectedDriver = (String) cmbDriver.getSelectedItem();
    String selectedVehicle = (String) cmbVehicle.getSelectedItem();

    if (selectedDriver == null || selectedVehicle == null) {
        JOptionPane.showMessageDialog(
            this, "Please select a driver and vehicle."
        );
        return;
    }

    String customer = txtCustomer.getText().trim();
    String contact = txtContactNumber.getText().trim(); 
    String pickup = txtPickup.getText().trim();
    String dropoff = txtDropOff.getText().trim();
    String pickupDate = txtPickupDate.getText().trim();
    String pickupTime = txtPickupTime.getText().trim();
    
    java.math.BigDecimal distance;

try {
    distance = new java.math.BigDecimal(
        txtDistance.getText().trim()
    );

    if (distance.compareTo(java.math.BigDecimal.ZERO) <= 0
            || distance.scale() > 2
            || distance.compareTo(
                new java.math.BigDecimal("99999999.99")) > 0) {

        JOptionPane.showMessageDialog(this,
            "Enter a valid distance greater than zero "
            + "with up to 2 decimal places.");
        return;
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
        "Please enter a valid delivery distance.");
    return;
}
    
    try {
    java.time.LocalDate date =
        java.time.LocalDate.parse(pickupDate);

    java.time.LocalTime time =
        java.time.LocalTime.parse(pickupTime);

    java.time.LocalDateTime pickupDateTime =
        java.time.LocalDateTime.of(date, time);

    if (pickupDateTime.isBefore(java.time.LocalDateTime.now())) {
        JOptionPane.showMessageDialog(this,
            "Pickup date and time cannot be in the past.");
        return;
    }

} catch (java.time.format.DateTimeParseException e) {
    JOptionPane.showMessageDialog(this,
        "Invalid pickup date or time.\n"
        + "Date format: YYYY-MM-DD\n"
        + "Time format: HH:mm (24-hour format)");
    return;
}

    if (customer.isEmpty() || pickup.isEmpty() || dropoff.isEmpty()) {
        JOptionPane.showMessageDialog(
            this, "Please complete all booking fields."
        );
        return;
    }
    
    if (!contact.matches("\\d{7,15}")) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter a valid contact number (7 to 15 digits)."
    );
    return;
}

    int driverId;
    int vehicleId;

    try {
        driverId = Integer.parseInt(selectedDriver.split(" - ")[0]);
        vehicleId = Integer.parseInt(selectedVehicle.split(" - ")[0]);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Invalid driver or vehicle selection."
        );
        return;
    }

    try (Connection con = DBConnection.connect()) {

        con.setAutoCommit(false);
        
        java.math.BigDecimal estimatedTotal;

String ratesSQL =
    "SELECT base_fee, rate_per_km "
    + "FROM delivery_rates WHERE rate_id = 1";

try (PreparedStatement ratesPst =
         con.prepareStatement(ratesSQL);
     ResultSet ratesRs = ratesPst.executeQuery()) {

    if (!ratesRs.next()) {
        JOptionPane.showMessageDialog(this,
            "Delivery rates were not found.");
        con.rollback();
        return;
    }

    java.math.BigDecimal baseFee =
        ratesRs.getBigDecimal("base_fee");

    java.math.BigDecimal ratePerKm =
        ratesRs.getBigDecimal("rate_per_km");

    estimatedTotal = baseFee.add(
        distance.multiply(ratePerKm)
    ).setScale(2, java.math.RoundingMode.HALF_UP);

    txtEstimatedTotal.setText(
        estimatedTotal.toPlainString()
    );
}

        try {

            // Reserve driver only if AVAILABLE
            String driverSQL =
                "UPDATE drivers SET status = 'UNAVAILABLE' "
                + "WHERE driver_id = ? AND status = 'AVAILABLE'";

            int driverUpdated;

            try (PreparedStatement pst =
                    con.prepareStatement(driverSQL)) {

                pst.setInt(1, driverId);
                driverUpdated = pst.executeUpdate();
            }

            if (driverUpdated != 1) {
                con.rollback();
                JOptionPane.showMessageDialog(
                    this,
                    "The driver is not available.\n"
                    + "Invalid booking, choose another driver."
                );
                return;
            }

            // Reserve vehicle only if AVAILABLE
            String vehicleSQL =
                "UPDATE vehicles SET status = 'UNAVAILABLE' "
                + "WHERE vehicle_id = ? AND status = 'AVAILABLE'";

            int vehicleUpdated;

            try (PreparedStatement pst =
                    con.prepareStatement(vehicleSQL)) {

                pst.setInt(1, vehicleId);
                vehicleUpdated = pst.executeUpdate();
            }

            if (vehicleUpdated != 1) {

                String status = "";

                try (PreparedStatement pst = con.prepareStatement(
                        "SELECT status FROM vehicles WHERE vehicle_id = ?")) {

                    pst.setInt(1, vehicleId);

                    try (ResultSet rs = pst.executeQuery()) {
                        if (rs.next()) {
                            status = rs.getString("status");
                        }
                    }
                }

                con.rollback();

                if ("MAINTENANCE".equalsIgnoreCase(status)) {
                    JOptionPane.showMessageDialog(
                        this,
                        "The vehicle is under maintenance.\n"
                        + "Invalid booking, choose another vehicle."
                    );
                } else {
                    JOptionPane.showMessageDialog(
                        this,
                        "The vehicle is not available.\n"
                        + "Invalid booking, choose another vehicle."
                    );
                }
                return;
            }

            // Save the booking
            String bookingSQL = 
    "INSERT INTO bookings "
    + "(customer_name, contact_number, pickup_location, "
    + "dropoff_location, pickup_date, pickup_time, "
    + "driver_id, vehicle_id, distance_km, estimated_total) "
    + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

            try (PreparedStatement pst =
                    con.prepareStatement(bookingSQL)) {

                pst.setString(1, customer);
                pst.setString(2, contact);
                pst.setString(3, pickup);
                pst.setString(4, dropoff);
                pst.setDate(5, java.sql.Date.valueOf(pickupDate));
                pst.setTime(6, java.sql.Time.valueOf(pickupTime + ":00"));
                pst.setInt(7, driverId);
                pst.setInt(8, vehicleId);
                pst.setBigDecimal(9, distance);
                pst.setBigDecimal(10, estimatedTotal);

                pst.executeUpdate();
            }

            con.commit();

        } catch (SQLException e) {
            con.rollback();
            throw e;
        }

        JOptionPane.showMessageDialog(
            this, "Successfully booked!"
        );

        loadDrivers();
        loadVehicles();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error adding booking:\n" + e.getMessage()
        );
    }
}
