    private void btnCalculateTotalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateTotalActionPerformed
        txtEstimatedTotal.setText("");

try {
    java.math.BigDecimal distance =
        new java.math.BigDecimal(txtDistance.getText().trim());

    if (distance.compareTo(java.math.BigDecimal.ZERO) <= 0) {
        JOptionPane.showMessageDialog(this,
            "Delivery distance must be greater than zero.");
        return;
    }

    String sql =
        "SELECT base_fee, rate_per_km "
        + "FROM delivery_rates WHERE rate_id = 1";

    try (Connection con = DBConnection.connect();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        if (rs.next()) {

            java.math.BigDecimal baseFee =
                rs.getBigDecimal("base_fee");

            java.math.BigDecimal ratePerKm =
                rs.getBigDecimal("rate_per_km");

            java.math.BigDecimal total =
                baseFee.add(distance.multiply(ratePerKm));

            total = total.setScale(
                2, java.math.RoundingMode.HALF_UP
            );

            txtEstimatedTotal.setText(total.toPlainString());

        } else {
            JOptionPane.showMessageDialog(this,
                "Delivery rates were not found.");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
        "Please enter a valid delivery distance.");

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
        "Error calculating delivery cost:\n" + e.getMessage());
}
    }//GEN-LAST:event_btnCalculateTotalActionPerformed

