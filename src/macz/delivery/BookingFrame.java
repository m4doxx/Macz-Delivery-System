    private void loadDrivers() {
    cmbDriver.removeAllItems();

    String sql = "SELECT driver_id, driver_name FROM drivers "
           + "WHERE status = 'AVAILABLE' ORDER BY driver_name";

    try (Connection con = DBConnection.connect();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            int id = rs.getInt("driver_id");
            String name = rs.getString("driver_name");

            cmbDriver.addItem(id + " - " + name);
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error loading drivers: " + e.getMessage()
        );
    }
}
