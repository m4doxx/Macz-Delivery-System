private void loadAssignments() {

    String sql =
        "SELECT b.booking_id, d.driver_name, "
        + "v.plate_number, b.status, "
        + "b.distance_km, b.estimated_total "
        + "FROM bookings b "
        + "LEFT JOIN drivers d ON b.driver_id = d.driver_id "
        + "LEFT JOIN vehicles v ON b.vehicle_id = v.vehicle_id "
        + "ORDER BY b.booking_id DESC";

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
            tableAssignment.getModel();

    model.setRowCount(0);

    try (java.sql.Connection con = DBConnection.connect();
         java.sql.PreparedStatement pst = con.prepareStatement(sql);
         java.sql.ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("booking_id"),
                rs.getString("driver_name"),
                rs.getString("plate_number"),
                rs.getString("status"),
                rs.getBigDecimal("distance_km"),
                rs.getBigDecimal("estimated_total")
            });
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading assignments:\n" + e.getMessage()
        );
    }
    updateRecordCount();
}
private void updateRecordCount() {
    int total = tableAssignment.getRowCount();
    lblTotalRecords.setText("Total Records: " + total);
}
private void searchAssignments() {

    String keyword = txtSearchAssignment.getText().trim();

    if (keyword.isEmpty()) {
        loadAssignments();
        return;
    }

    String sql =
        "SELECT b.booking_id, d.driver_name, "
        + "v.plate_number, b.status, "
        + "b.distance_km, b.estimated_total "
        + "FROM bookings b "
        + "LEFT JOIN drivers d ON b.driver_id = d.driver_id "
        + "LEFT JOIN vehicles v ON b.vehicle_id = v.vehicle_id "
        + "WHERE CAST(b.booking_id AS CHAR) = ? "
        + "OR d.driver_name LIKE ? "
        + "OR v.plate_number LIKE ? "
        + "ORDER BY b.booking_id DESC";

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        tableAssignment.getModel();

    model.setRowCount(0);

    try (java.sql.Connection con = DBConnection.connect();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, keyword);
        pst.setString(2, "%" + keyword + "%");
        pst.setString(3, "%" + keyword + "%");

        try (java.sql.ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("booking_id"),
                    rs.getString("driver_name"),
                    rs.getString("plate_number"),
                    rs.getString("status"),
                    rs.getBigDecimal("distance_km"),
                    rs.getBigDecimal("estimated_total")
                });
            }
            if (model.getRowCount() == 0) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "No assignments found for: " + keyword,
        "Search Result",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
}
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error searching assignments:\n" + e.getMessage()
        );
    }
    updateRecordCount();
}

