    private void loadDeliveryRates() {

    String sql =
        "SELECT base_fee, rate_per_km "
        + "FROM delivery_rates WHERE rate_id = 1";

    try (Connection con = DBConnection.connect();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        if (rs.next()) {
            txtBaseFee.setText(
                rs.getBigDecimal("base_fee").toPlainString()
            );

            txtRatePerKm.setText(
                rs.getBigDecimal("rate_per_km").toPlainString()
            );
        } else {
            JOptionPane.showMessageDialog(this,
                "Delivery rates were not found in the database.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error loading delivery rates:\n" + e.getMessage());
    }
}
