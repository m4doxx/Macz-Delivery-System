    private void btnSaveRatesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveRatesActionPerformed
        String role = UserSession.getRole();

if (!"ADMIN".equals(role) && !"STAFF".equals(role)) {
    JOptionPane.showMessageDialog(this,
        "Access denied. Only ADMIN and STAFF can update rates.");
    return;
}

try {
    java.math.BigDecimal baseFee =
        new java.math.BigDecimal(txtBaseFee.getText().trim());

    java.math.BigDecimal ratePerKm =
        new java.math.BigDecimal(txtRatePerKm.getText().trim());

    if (baseFee.compareTo(java.math.BigDecimal.ZERO) < 0
            || ratePerKm.compareTo(java.math.BigDecimal.ZERO) <= 0) {

        JOptionPane.showMessageDialog(this,
            "Base fee cannot be negative, and rate per km must be greater than zero.");
        return;
    }

    if (baseFee.scale() > 2 || ratePerKm.scale() > 2
            || baseFee.compareTo(new java.math.BigDecimal("99999999.99")) > 0
            || ratePerKm.compareTo(new java.math.BigDecimal("99999999.99")) > 0) {

        JOptionPane.showMessageDialog(this,
            "Enter valid rates with up to 2 decimal places.");
        return;
    }

    String sql =
        "UPDATE delivery_rates SET base_fee = ?, rate_per_km = ? "
        + "WHERE rate_id = 1";

    try (Connection con = DBConnection.connect();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setBigDecimal(1, baseFee);
        pst.setBigDecimal(2, ratePerKm);

        int updated = pst.executeUpdate();

        if (updated > 0) {
            JOptionPane.showMessageDialog(this,
                "Delivery rates updated successfully!");
            loadDeliveryRates();
        } else {
            JOptionPane.showMessageDialog(this,
                "Delivery rates record not found.");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
        "Please enter valid numeric delivery rates.");

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
        "Error updating delivery rates:\n" + e.getMessage());
}
    }//GEN-LAST:event_btnSaveRatesActionPerformed

