    private void btnSaveChangesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveChangesActionPerformed
        String fullName = txtFullName.getText().trim();
String phoneNumber = txtPhoneNumber.getText().trim();

if (fullName.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Full Name cannot be empty.");
    return;
}

if (fullName.length() > 100 || phoneNumber.length() > 20) {
    JOptionPane.showMessageDialog(
        this, "Full Name or Phone Number is too long."
    );
    return;
}

String sql = "UPDATE users SET full_name = ?, phone_number = ? "
           + "WHERE user_id = ?";

try (Connection con = DBConnection.connect();
     PreparedStatement pst = con.prepareStatement(sql)) {

    pst.setString(1, fullName);
    pst.setString(2, phoneNumber);
    pst.setInt(3, UserSession.getUserId());

    int updated = pst.executeUpdate();

    if (updated > 0) {
        JOptionPane.showMessageDialog(
            this, "Profile updated successfully!"
        );
        loadProfile();
    } else {
        JOptionPane.showMessageDialog(
            this, "Profile not found. No changes saved."
        );
    }

} catch (SQLException e) {
    JOptionPane.showMessageDialog(
        this, "Error saving profile: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnSaveChangesActionPerformed

