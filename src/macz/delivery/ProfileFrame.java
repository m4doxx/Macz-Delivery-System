private void loadProfile() {

    int userId = UserSession.getUserId();

    String sql = "SELECT full_name, username, phone_number, role "
               + "FROM users WHERE user_id = ?";

    try (Connection con = DBConnection.connect();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, userId);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                txtFullName.setText(rs.getString("full_name"));
                txtUsername.setText(rs.getString("username"));
                txtPhoneNumber.setText(rs.getString("phone_number"));
                txtRole.setText(rs.getString("role"));
            } else {
                JOptionPane.showMessageDialog(
                    this, "User profile not found."
                );
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error loading profile: " + e.getMessage()
        );
    }
}
