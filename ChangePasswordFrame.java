    private void btnSavePasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSavePasswordActionPerformed
        char[] currentPassword = txtCurrentPassword.getPassword();
char[] newPassword = txtNewPassword.getPassword();
char[] confirmPassword = txtConfirmPassword.getPassword();

try {
    if (currentPassword.length == 0 ||
        newPassword.length == 0 ||
        confirmPassword.length == 0) {

        JOptionPane.showMessageDialog(
            this, "Please complete all password fields."
        );
        return;
    }

    if (newPassword.length < 8) {
        JOptionPane.showMessageDialog(
            this, "New password must have at least 8 characters."
        );
        return;
    }

    if (!java.util.Arrays.equals(newPassword, confirmPassword)) {
        JOptionPane.showMessageDialog(
            this, "New passwords do not match."
        );
        return;
    }

    String sql = "SELECT password FROM users WHERE user_id = ?";

    try (Connection con = DBConnection.connect();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, UserSession.getUserId());

        try (ResultSet rs = pst.executeQuery()) {

            if (!rs.next()) {
                JOptionPane.showMessageDialog(
                    this, "User account not found."
                );
                return;
            }

            String storedPassword = rs.getString("password");

            if (!PasswordUtil.verifyPassword(
                    currentPassword, storedPassword)) {

                JOptionPane.showMessageDialog(
                    this, "Current password is incorrect."
                );
                return;
            }

            if (java.util.Arrays.equals(currentPassword, newPassword)) {
                JOptionPane.showMessageDialog(
                    this, "New password must be different from the current password."
                );
                return;
            }

            String newHash = PasswordUtil.hashPassword(newPassword);

            String updateSql =
                "UPDATE users SET password = ? "
                + "WHERE user_id = ? AND password = ?";

            try (PreparedStatement update =
                    con.prepareStatement(updateSql)) {

                update.setString(1, newHash);
                update.setInt(2, UserSession.getUserId());
                update.setString(3, storedPassword);

                int updated = update.executeUpdate();

                if (updated > 0) {
                    JOptionPane.showMessageDialog(
                        this, "Password changed successfully!"
                    );

                    txtCurrentPassword.setText("");
                    txtNewPassword.setText("");
                    txtConfirmPassword.setText("");

                } else {
                    JOptionPane.showMessageDialog(
                        this, "Password was not updated. Please try again."
                    );
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Database Error: " + e.getMessage()
        );
    }

} finally {
    java.util.Arrays.fill(currentPassword, '\0');
    java.util.Arrays.fill(newPassword, '\0');
    java.util.Arrays.fill(confirmPassword, '\0');
}
    }//GEN-LAST:event_btnSavePasswordActionPerformed

